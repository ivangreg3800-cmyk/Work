  const pass=mapping.has(expected.id)&&actual.length===targetEdges.length&&targetEdges.every(([a,b,label])=>mapping.has(b)&&actual.filter(f=>f.target===mapping.get(b)&&(!label||normalize(f.name)===normalize(label))).length===1);
